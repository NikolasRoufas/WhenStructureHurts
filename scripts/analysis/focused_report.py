"""Generate FOCUSED_PILOT_REPORT.md from build.py outputs (tables only; no new computation).
    python scripts/analysis/focused_report.py <analysis_dir> <exp1_label> [<exp0_label>] [--notes notes.md] > REPORT.md
Every number is read from the CSV/JSON files named in the report, which carry the run ids and
input hashes (provenance.json)."""
import csv
import json
import sys
from pathlib import Path

d = Path(sys.argv[1])
e1 = sys.argv[2]
e0 = sys.argv[3] if len(sys.argv) > 3 and not sys.argv[3].startswith("--") else None
notes = Path(sys.argv[sys.argv.index("--notes") + 1]) if "--notes" in sys.argv else None
REPS = ["R0", "R1", "R2", "R3", "R4", "R4P", "R5"]
DSN = {"musique": "MuSiQue", "2wikimultihopqa": "2Wiki", "hotpotqa": "HotpotQA", "hover": "HoVer", "fever": "FEVER"}


def rows(name):
    p = d / name
    return list(csv.DictReader(open(p))) if p.exists() and p.stat().st_size else []


def f(x, nd=3):
    if x in ("", None):
        return "–"
    try:
        return f"{float(x):.{nd}f}"
    except ValueError:
        return str(x)


def ci(x, nd=3):
    if not x:
        return "–"
    a, b = json.loads(x)
    return f"[{a:+.{nd}f}, {b:+.{nd}f}]"


out = []
w = out.append
summ = json.loads((d / "run_summary.json").read_text())
prov = json.loads((d / "provenance.json").read_text())
w("# Focused pilot report (Stage A): MuSiQue + 2WikiMultiHopQA, 200 questions\n")
w("_Auto-generated by `scripts/analysis/focused_report.py` from the analysis outputs in this directory. "
  "Exploratory pilot: no interval or p-value below is confirmatory._\n")
w("## 1. Runs and execution health\n")
w("| label | experiment | run dir | status | records | unavailable | generation errors | pipeline errors | finish reasons | settings identical | wall clock (s) |")
w("|---|---|---|---|---|---|---|---|---|---|---|")
for lab, s in summ.items():
    if lab.startswith("_"):
        continue
    w(f"| {lab} | {s['experiment']} | `{prov[lab]['run_dir']}` | {s['status']} | {s['n_records']} | {s['n_unavailable']} | "
      f"{s['n_generation_error']} | {s['n_pipeline_error']} | {s['finish_reasons']} | {s['consistency']} | {f(s['wall_clock_s'], 0)} |")
w("\nInput hashes (sha256 of every run file) and git commits are in `provenance.json`.\n")

ab = rows(f"{e1}_absolute.csv")
w("## 2. Exp1 absolute results\n")
for ds in ("musique", "2wikimultihopqa"):
    w(f"### {DSN[ds]}\n")
    w("| setting | rep | n | EM [95% CI] | F1 | coverage | evidence tok | overhead tok | answer in evidence | sufficiency proxy | latency (s) |")
    w("|---|---|---|---|---|---|---|---|---|---|---|")
    for r in ab:
        if r["dataset"] != ds:
            continue
        c = json.loads(r["score_ci"]) if r["score_ci"] else None
        w(f"| {r['setting']} | {r['representation']} | {r['n_questions']} | {f(r['score'])} "
          f"[{c[0]:.2f}, {c[1]:.2f}] | {f(r['f1'])} | {f(r['coverage'])} | {f(r['evidence_tokens'], 0)} | "
          f"{f(r['overhead_tokens'], 0)} | {f(r['answer_in_evidence'])} | {f(r['evidence_sufficient'])} | {f(r['latency_s_mean'], 2)} |")
    w("")

co = rows(f"{e1}_contrasts.csv")
w("## 3. Primary contrasts (Protocol A, EM, all edge strata pooled)\n")
w("Δ = EM(b) − EM(a); paired question-level bootstrap (2000 resamples, seed 0). `identical` = questions whose two evidence "
  "blocks are byte-identical (their difference is 0 by construction); `informative` = the estimate on the remaining pairs; "
  "coverage Δ = paired difference in answered rate. McNemar (exact, discordant pairs) and d_z are secondary.\n")
w("| dataset | contrast | n | Δ EM | 95% CI | p (boot) | b better / a better | identical | informative n: Δ [CI] | coverage Δ | McNemar p | d_z |")
w("|---|---|---|---|---|---|---|---|---|---|---|---|")
for ds in ("musique", "2wikimultihopqa"):
    for con in ("R1-R0", "R5-R1", "R4-R5"):
        for r in co:
            if r["dataset"] == ds and r["setting"] == "A" and r["edge_stratum"] == "all" and r["contrast"] == con and r["metric"] == "em":
                w(f"| {DSN[ds]} | {con} | {r['n_paired']} | {f(r['delta'])} | {ci(r['ci'])} | {f(r['p_boot'])} | "
                  f"{r['n_b_better']} / {r['n_a_better']} | {r['n_identical_evidence']} | {r['informative_n']}: "
                  f"{f(r['informative_delta'])} {ci(r['informative_ci'])} | {f(r['coverage_delta'])} | "
                  f"{f(r['mcnemar_p_secondary'])} | {f(r['d_z'], 2)} |")
w("\n### 3a. Same contrasts by edge stratum (Protocol A; derived structure, none human-verified)\n")
w("| dataset | contrast | stratum | n | Δ EM | 95% CI | b better / a better | identical |")
w("|---|---|---|---|---|---|---|---|")
for r in co:
    if r["setting"] == "A" and r["edge_stratum"] != "all" and r["metric"] == "em" and r["contrast"] in ("R5-R1", "R4-R5"):
        w(f"| {DSN[r['dataset']]} | {r['contrast']} | {r['edge_stratum'].replace('edge_stratum=', '')} | {r['n_paired']} | "
          f"{f(r['delta'])} | {ci(r['ci'])} | {r['n_b_better']} / {r['n_a_better']} | {r['n_identical_evidence']} |")
w("\n### 3b. Secondary contrasts (Protocol A, EM)\n")
w("| dataset | contrast | n | Δ EM | 95% CI | identical | coverage Δ |")
w("|---|---|---|---|---|---|---|")
for r in co:
    if r["setting"] == "A" and r["edge_stratum"] == "all" and r["metric"] == "em" and r["contrast"] in ("R2-R1", "R3-R5", "R4P-R4"):
        w(f"| {DSN[r['dataset']]} | {r['contrast']} | {r['n_paired']} | {f(r['delta'])} | {ci(r['ci'])} | "
          f"{r['n_identical_evidence']} | {f(r['coverage_delta'])} |")

w("\n## 4. Protocol B (budget-controlled; never pooled with A)\n")
w("| dataset | setting | contrast | n | Δ EM | 95% CI | identical | coverage Δ |")
w("|---|---|---|---|---|---|---|---|")
for r in co:
    if r["setting"] != "A" and r["edge_stratum"] == "all" and r["metric"] == "em" and r["contrast"] in ("R1-R0", "R5-R1", "R4-R5"):
        w(f"| {DSN[r['dataset']]} | {r['setting']} | {r['contrast']} | {r['n_paired']} | {f(r['delta'])} | {ci(r['ci'])} | "
          f"{r['n_identical_evidence']} | {f(r['coverage_delta'])} |")
acc = rows(f"{e1}_protocol_accounting.csv")
w("\n### 4a. What each condition showed (information accounting)\n")
w("`kept` = fraction of the fact set shown; `answer-bearing dropped` = facts containing the answer string that were cut, per question; "
  "`required dropped` counts gold-support facts cut (for MuSiQue support is paragraph-level, so every sentence of a gold paragraph "
  "counts as required and `required facts fit` is 0 by construction).\n")
w("| dataset | condition | facts shown | evidence tok | overhead tok | kept | required dropped | answer-bearing dropped | required facts fit | sufficiency | answer in evidence |")
w("|---|---|---|---|---|---|---|---|---|---|---|")
for r in acc:
    cond = r["condition"]
    keep = {k: v for k, v in (kv.split("=", 1) for kv in cond.split(",") if "=" in kv)}
    rep = keep.get("representation")
    if rep not in ("R0", "R1", "R4", "R5"):
        continue
    sett = "A" if keep.get("protocol") == "A" else f"B {keep.get('budget', '').replace('content:', '')}x {keep.get('policy')}"
    w(f"| {DSN[r['dataset']]} | {sett} {rep} | {f(r['facts_shown'], 1)} | {f(r['evidence_tokens'], 0)} | {f(r['overhead_tokens'], 0)} | "
      f"{f(r.get('facts_kept_frac'))} | {f(r.get('required_dropped'), 2)} | {f(r.get('answer_bearing_dropped'), 2)} | "
      f"{f(r.get('required_fit_budget_frac'))} | {f(r['evidence_sufficient'])} | {f(r['answer_in_evidence'])} |")

w("\n## 5. Error taxonomy (every incorrect record; none removed)\n")
w("`abstained` = replied *insufficient evidence*; `missing_evidence` = gold answer string absent from what was shown; "
  "`evaluation_mismatch_candidate` = EM 0 but token F1 ≥ 0.5 (possible alias/format mismatch, needs manual check); "
  "`reasoning_error_evidence_present` = answered, wrong, answer string present.\n")
tax = rows(f"{e1}_error_taxonomy.csv")
cats = ["abstained", "missing_evidence", "evaluation_mismatch_candidate", "reasoning_error_evidence_present", "generation_failure"]
w("| dataset | setting | rep | incorrect | " + " | ".join(cats) + " |")
w("|---|---|---|---|" + "---|" * len(cats))
for r in tax:
    if r["setting"] in ("A", "B 1.0x per_representation"):
        w(f"| {DSN[r['dataset']]} | {r['setting']} | {r['condition']} | {r['n_incorrect']} | " +
          " | ".join(r.get(c) or "0" for c in cats) + " |")
w("\n(R2 counts are summed over its three shuffle seeds.)\n")

sub = rows(f"{e1}_subgroups.csv")
w("## 6. Subgroups (exploratory; Protocol A)\n")
w("| dataset | subgroup | contrast | n | EM a | EM b | Δ | 95% CI |")
w("|---|---|---|---|---|---|---|---|")
for r in sub:
    w(f"| {DSN[r['dataset']]} | {r['subgroup']} | {r['contrast']} | {r['n_paired']} | {f(r['score_a'])} | {f(r['score_b'])} | "
      f"{f(r['delta'])} | {ci(r['ci'])} |")

sens = rows(f"{e1}_em_sensitivity_secondary.csv")
if sens:
    w("\n## 7. Secondary metric check: EM with diacritics folded\n")
    w("| dataset | contrast | Δ | 95% CI | records changed by folding (dataset, Protocol A) |")
    w("|---|---|---|---|---|")
    for r in sens:
        w(f"| {DSN[r['dataset']]} | {r['contrast']} | {f(r['delta'])} | {ci(r['ci'])} | {r['n_records_changed_by_folding_in_dataset']} |")
ss = rows(f"{e1}_sample_size.csv")
if ss:
    w("\n## 8. Sample size for a confirmatory test (PILOT_PROTOCOL §8.3)\n")
    w("n for 80% power to detect |ΔEM| = 0.03, two-sided α = 0.05/6, pilot SD of paired differences inflated by 20%.\n")
    w("| dataset | contrast | pilot SD | discordant rate | n required | remaining dev pool | MDE at full pool |")
    w("|---|---|---|---|---|---|---|")
    for r in ss:
        w(f"| {DSN[r['dataset']]} | {r['contrast']} | {f(r['sd_paired_diff'])} | {f(r['discordant_rate'], 2)} | {r['n_required']} | "
          f"{r['remaining_dev_pool']} | {f(r['mde_at_full_pool'])} |")

if e0:
    w("\n## 9. Exp0 retrieved-evidence baselines\n")
    w("| dataset | system | n | EM [95% CI] | F1 | coverage | evidence tok | units | support coverage | answer in evidence | latency (s) |")
    w("|---|---|---|---|---|---|---|---|---|---|---|")
    for r in rows(f"{e0}_absolute.csv"):
        c = json.loads(r["score_ci"]) if r["score_ci"] else [0, 0]
        w(f"| {DSN[r['dataset']]} | {r['system']} | {r['n_questions']} | {f(r['score'])} [{c[0]:.2f}, {c[1]:.2f}] | {f(r['f1'])} | "
          f"{f(r['coverage'])} | {f(r['evidence_tokens'], 0)} | {f(r['n_units_mean'], 1)} | {f(r['support_coverage'])} | "
          f"{f(r['answer_in_evidence'])} | {f(r['latency_s_mean'], 2)} |")
    w("\n| dataset | contrast | n | Δ EM | 95% CI | p (boot) | identical | coverage Δ |")
    w("|---|---|---|---|---|---|---|---|")
    for r in rows(f"{e0}_contrasts.csv"):
        if r["metric"] == "em":
            w(f"| {DSN[r['dataset']]} | {r['contrast']} | {r['n_paired']} | {f(r['delta'])} | {ci(r['ci'])} | {f(r['p_boot'])} | "
              f"{r['n_identical_evidence']} | {f(r['coverage_delta'])} |")

if notes and notes.exists():
    w("\n" + notes.read_text())
print("\n".join(out))
